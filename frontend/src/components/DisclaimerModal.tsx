"use client";

import React, { useEffect, useRef, useState } from "react";
import Link from "next/link";
import Dialog from "@/components/Dialog";

const ACK_KEY = "sapling_disclaimer_ack";

export function DisclaimerModal({
  open: controlledOpen,
  onClose,
}: {
  open?: boolean;
  onClose?: () => void;
} = {}) {
  const isControlled = controlledOpen !== undefined;
  const [internalOpen, setInternalOpen] = useState(false);
  const open = isControlled ? controlledOpen : internalOpen;

  useEffect(() => {
    if (isControlled) return;
    const acked = typeof window !== "undefined" && localStorage.getItem(ACK_KEY) === "true";
    if (!acked) setInternalOpen(true);
  }, [isControlled]);

  const gotIt = useRef<HTMLButtonElement>(null);

  const ack = () => {
    localStorage.setItem(ACK_KEY, "true");
    if (isControlled) onClose?.();
    else setInternalOpen(false);
  };

  // Not dismissible: the student acknowledges it, or follows a policy link
  // (which acknowledges it too). Focus starts on "Got it", not the first link.
  return (
    <Dialog open={open} onClose={ack} dismissible={false} labelledBy="disclaimer-title" width="480px" zIndex={220} initialFocusRef={gotIt}>
        <div className="label-micro mb-2">Heads up</div>
        <div id="disclaimer-title" className="h-serif text-2xl mb-2.5">Sapling uses AI</div>
        <div className="text-md text-text-dim leading-[1.6] mb-4">
          <p className="mt-0 mx-0 mb-2.5">
            Responses are generated by a large language model and can be wrong, incomplete, or
            inconsistent. Use Sapling as a study partner — not a source of truth. Always cross-check
            important claims against your course materials, and never paste sensitive personal
            information into chat.
          </p>
          <p className="m-0">
            Check citations and facts against primary sources. Your conversations may be used to
            improve the product. Don&apos;t share passwords, IDs, or private info.
          </p>
        </div>
        <div
          className="flex flex-wrap items-center justify-between gap-3 pt-3 border-t border-t-border text-md"
        >
          <div className="flex flex-wrap gap-3.5">
            <Link href="/terms" onClick={ack} className="text-accent no-underline">
              Terms of Service
            </Link>
            <Link href="/privacy" onClick={ack} className="text-accent no-underline">
              Privacy Policy
            </Link>
          </div>
          <button ref={gotIt} className="btn btn--primary" onClick={ack}>Got it</button>
        </div>
    </Dialog>
  );
}
